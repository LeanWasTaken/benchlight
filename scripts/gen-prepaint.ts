import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// js/prepaint.js as an importable string, so the Nuxt module and the Vite plugin need no
// node:fs (a consumer's typecheck covers shipped TypeScript, and may lack @types/node).
const root = join(import.meta.dir, '..')
const prepaint = readFileSync(join(root, 'js/prepaint.js'), 'utf8').trim()
const hash = createHash('sha256').update(prepaint).digest('base64')

writeFileSync(
  join(root, 'js/prepaint-script.mjs'),
  `// Generated by scripts/gen-prepaint.ts from js/prepaint.js. Do not edit.
export const PREPAINT = ${JSON.stringify(prepaint)}
// CSP source expression for the inline script above: script-src ${'${PREPAINT_CSP_HASH}'}
export const PREPAINT_CSP_HASH = ${JSON.stringify(`'sha256-${hash}'`)}
`
)
writeFileSync(
  join(root, 'js/prepaint-script.d.mts'),
  `/** The no-flash appearance script (js/prepaint.js), ready to inline in <head>. */
export declare const PREPAINT: string
/** CSP source expression, quoted, for the exact PREPAINT text: 'sha256-…'. */
export declare const PREPAINT_CSP_HASH: string
`
)
console.log('wrote js/prepaint-script.mjs and js/prepaint-script.d.mts')
