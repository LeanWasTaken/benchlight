// @vitest-environment node
import { beforeEach, describe, expect, it, vi } from 'vitest'
import COMPONENTS from '../../dist/vue/components.json'
import * as vueEntry from '../../vue/index'
import { PREPAINT } from '../../js/prepaint-script.mjs'
import { prefixedName } from '../../nuxt/module'

const kit = vi.hoisted(() => ({
  addComponent: vi.fn(),
  addImports: vi.fn()
}))

vi.mock('@nuxt/kit', () => ({
  ...kit,
  createResolver: () => ({ resolve: (path: string) => `/pkg/nuxt/${path}` }),
  defineNuxtModule: <T>(definition: T) => definition
}))

interface TestNuxt {
  options: {
    css: string[]
    app: { head: { script?: Array<Record<string, unknown>> } }
    build: { transpile: string[] }
    vite: { optimizeDeps?: { exclude?: string[]; include?: string[] } }
  }
}

type Definition = {
  meta: { name: string; configKey: string }
  defaults: { fonts: boolean; autoImports: boolean | { prefix?: string }; prepaint?: boolean }
  setup: (
    options: { fonts: boolean; autoImports?: boolean | { prefix?: string }; prepaint?: boolean },
    nuxt: TestNuxt
  ) => void
}

const load = async () => (await import('../../nuxt/module')).default as unknown as Definition

const makeNuxt = (): TestNuxt => ({
  options: {
    css: ['/app/main.css'],
    app: { head: { script: [{ src: '/existing.js' }] } },
    build: { transpile: ['other'] },
    vite: { optimizeDeps: { exclude: ['already'], include: ['kept'] } }
  }
})

describe('nuxt module', () => {
  beforeEach(() => {
    kit.addComponent.mockClear()
    kit.addImports.mockClear()
  })

  it('registers under the benchlight config key with fonts on by default', async () => {
    const module = await load()
    expect(module.meta.name).toBe('benchlight')
    expect(module.meta.configKey).toBe('benchlight')
    expect(module.defaults).toEqual({ fonts: true, autoImports: true, prepaint: true })
  })

  it('puts fonts then the library css ahead of the app css', async () => {
    const nuxt = makeNuxt()
    ;(await load()).setup({ fonts: true, autoImports: true }, nuxt)
    expect(nuxt.options.css).toEqual([
      '/pkg/nuxt/../css/fonts.css',
      '/pkg/nuxt/../css/index.css',
      '/app/main.css'
    ])
  })

  it('omits fonts.css when fonts is off', async () => {
    const nuxt = makeNuxt()
    ;(await load()).setup({ fonts: false, autoImports: true }, nuxt)
    expect(nuxt.options.css).toEqual(['/pkg/nuxt/../css/index.css', '/app/main.css'])
  })

  it('prepends the prepaint script to the head scripts', async () => {
    const nuxt = makeNuxt()
    ;(await load()).setup({ fonts: true, autoImports: true }, nuxt)
    expect(nuxt.options.app.head.script).toEqual([
      { innerHTML: PREPAINT, tagPosition: 'head' },
      { src: '/existing.js' }
    ])
  })

  it('leaves the head scripts alone with prepaint: false', async () => {
    const nuxt = makeNuxt()
    ;(await load()).setup({ fonts: true, autoImports: true, prepaint: false }, nuxt)
    expect(nuxt.options.app.head.script).toEqual([{ src: '/existing.js' }])
  })

  it('registers every compiled component by its Bl name', async () => {
    ;(await load()).setup({ fonts: true, autoImports: true }, makeNuxt())
    expect(kit.addComponent).toHaveBeenCalledWith({
      name: 'BlButton',
      filePath: '/pkg/nuxt/../dist/vue/components/BlButton.vue.js'
    })
    expect(kit.addComponent).toHaveBeenCalledTimes(COMPONENTS.length)
    // components.json is generated by build:vue; it must list exactly the library's components
    expect([...COMPONENTS]).toEqual(
      Object.keys(vueEntry)
        .filter((name) => /^Bl[A-Z]/.test(name))
        .sort()
    )
  })

  const names = [
    'useAppearance',
    'useScrollLifted',
    'useReducedMotion',
    'useMarquee',
    'useFollowScroll',
    'riseDelay',
    'ansiToSegments',
    'useToast'
  ]
  type Entry = { name: string; as: string; from: string }

  it('auto-imports the composables and helpers from the vue entry with the Bl prefix', async () => {
    ;(await load()).setup({ fonts: true, autoImports: true }, makeNuxt())
    const imports = kit.addImports.mock.calls[0]![0] as Entry[]
    expect(imports.map((entry) => entry.name)).toEqual(names)
    expect(imports).toContainEqual({
      name: 'useToast',
      as: 'useBlToast',
      from: '/pkg/nuxt/../dist/vue/index.js'
    })
    expect(imports.map((entry) => entry.as)).toEqual(names.map((name) => prefixedName(name, 'Bl')))
    expect(new Set(imports.map((entry) => entry.from))).toEqual(
      new Set(['/pkg/nuxt/../dist/vue/index.js'])
    )
  })

  it('applies a custom prefix and an empty prefix restores the bare names', async () => {
    ;(await load()).setup({ fonts: true, autoImports: { prefix: 'Acme' } }, makeNuxt())
    const custom = kit.addImports.mock.calls[0]![0] as Entry[]
    expect(custom.map((entry) => entry.as)).toContain('useAcmeToast')
    expect(custom.map((entry) => entry.as)).toContain('acmeRiseDelay')
    kit.addImports.mockClear()
    ;(await load()).setup({ fonts: true, autoImports: { prefix: '' } }, makeNuxt())
    const bare = kit.addImports.mock.calls[0]![0] as Entry[]
    expect(bare.map((entry) => entry.as)).toEqual(names)
  })

  it('uses the default prefix for an options object without one', async () => {
    ;(await load()).setup({ fonts: true, autoImports: {} }, makeNuxt())
    const imports = kit.addImports.mock.calls[0]![0] as Entry[]
    expect(imports.map((entry) => entry.as)).toContain('useBlToast')
  })

  it('skips the composable auto-imports when autoImports is off, keeping components', async () => {
    ;(await load()).setup({ fonts: true, autoImports: false }, makeNuxt())
    expect(kit.addImports).not.toHaveBeenCalled()
    expect(kit.addComponent).toHaveBeenCalled()
  })

  it('transpiles the package and keeps it out of vite pre-bundling', async () => {
    const nuxt = makeNuxt()
    ;(await load()).setup({ fonts: true, autoImports: true }, nuxt)
    expect(nuxt.options.build.transpile).toEqual(['other', 'benchlight'])
    expect(nuxt.options.vite.optimizeDeps).toEqual({
      exclude: ['already', 'benchlight'],
      include: ['kept']
    })
  })

  it('creates optimizeDeps when the app has none', async () => {
    const nuxt = makeNuxt()
    nuxt.options.vite = {}
    ;(await load()).setup({ fonts: true, autoImports: true }, nuxt)
    expect(nuxt.options.vite.optimizeDeps).toEqual({ exclude: ['benchlight'] })
  })
})

describe('prefixedName', () => {
  it('puts the prefix after use for use* names', () => {
    expect(prefixedName('useToast', 'Bl')).toBe('useBlToast')
  })

  it('prepends a lower-cased prefix to other names', () => {
    expect(prefixedName('riseDelay', 'Bl')).toBe('blRiseDelay')
    expect(prefixedName('ansiToSegments', 'Acme')).toBe('acmeAnsiToSegments')
  })

  it('returns the name unchanged for an empty prefix', () => {
    expect(prefixedName('useToast', '')).toBe('useToast')
    expect(prefixedName('riseDelay', '')).toBe('riseDelay')
  })

  it('keeps the inner capitals of a camel-cased prefix', () => {
    expect(prefixedName('useToast', 'AcmeUi')).toBe('useAcmeUiToast')
    expect(prefixedName('riseDelay', 'AcmeUi')).toBe('acmeUiRiseDelay')
    expect(prefixedName('useToast', 'acme')).toBe('useAcmeToast')
  })

  it('does not treat a lower-case word starting with use as a composable', () => {
    expect(prefixedName('user', 'Bl')).toBe('blUser')
  })
})
